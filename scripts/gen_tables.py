"""Write dsp/coopiano_tables.lib from the reference extraction (build/ref).

Every table here is a fixed draw or a solve of the C++ model that a streaming
Faust program cannot redo per sample: the bridge admittance (a random modal
sum), the per-key tuning draws, the post-contact excitation level that scales
the action noises, and the soundboard's modal amplitudes fitted to its
equalized impulse response.
"""
import numpy as np, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from fit_board import fit, fit_many, synth

REF = sys.argv[1] if len(sys.argv) > 1 else "build/ref"
OUT = sys.argv[2] if len(sys.argv) > 2 else "dsp/coopiano_tables.lib"

def wf(name, values, doc, digits=10):
    body = ",".join(("%.*g" % (digits, v)) for v in values)
    return "// %s\n%s = waveform{%s};\n\n" % (doc, name, body)

adm = np.loadtxt(os.path.join(REF, "admittance.txt"))
mean_re = float(open(os.path.join(REF, "admittance.txt")).readline().split()[2])
keys = np.loadtxt(os.path.join(REF, "keys.txt"))
strike = np.loadtxt(os.path.join(REF, "strike.txt"))
board = np.loadtxt(os.path.join(REF, "board.txt"))
ir = np.fromfile(os.path.join(REF, "board_ir.f64"))
N = ir.size // 2
# Region responses (head + shared tail, as Engine hears an impulse in one
# region): one complex amplitude per mode, region and channel, all fitted
# with the Gram matrix of the base fit.
regions = [np.fromfile(os.path.join(REF, "region_%d.f64" % r)).reshape(-1, 2) for r in range(4)]
targets = [ir[:N], ir[N:]] + [reg[:, c] for reg in regions for c in (0, 1)]
fits = fit_many(board, targets, 1e-6)
AL, AR = fits[0], fits[1]
region_amps = fits[2:]
region_errs = []
for A, t in zip(region_amps, targets[2:]):
    y = synth(board, A, t.size)
    region_errs.append(20 * np.log10(np.sqrt(np.sum((y - t) ** 2) / np.sum(t ** 2))))
errs = []
for A, r in ((AL, ir[:N]), (AR, ir[N:])):
    y = synth(board, A, N)
    errs.append(20 * np.log10(np.sqrt(np.sum((y - r) ** 2) / np.sum(r ** 2))))

vel = np.unique(strike[:, 1])
tp = strike[:, 2].reshape(88, vel.size)

out = []
out.append('''//################################ coopiano_tables.lib ##########################################
// Generated by scripts/gen_tables.py from the reference extraction of coopiano's
// piano.hpp (ref/dump.cpp). Do not edit: run `make tables`.
//
// Soundboard fit: %d modes, relative error %.1f dB (L) and %.1f dB (R) against
// make_soundboard_ir over %d samples; the regions' responses (spread 0.7,
// position_depth 0.5) from %.1f to %.1f dB.
//###############################################################################################

declare name "coopiano_tables";

''' % (board.shape[0], errs[0], errs[1], N, min(region_errs), max(region_errs)))
out.append("// Mean of Re(Y) over the table, in s/kg (BridgeAdmittance::mean_re).\nadm_mean = %.17g;\n\n" % mean_re)
out.append(wf("adm_re", adm[:, 0], "Re of the bridge admittance at 0..12000 Hz, 1 Hz apart (s/kg)."))
out.append(wf("adm_im", adm[:, 1], "Im of the bridge admittance at 0..12000 Hz, 1 Hz apart (s/kg)."))
out.append(wf("key_u", keys[:, 22:25].reshape(-1), "Per-key tuning draws (0.8 + 0.4 u) of strings 0..2, key-major from A0; 0 for one-string keys.", 17))
out.append("// Velocities of the tone-peak grid: 0.02 * 50^(j/%d), j = 0..%d.\ntp_nv = %d;\n\n" % (vel.size - 1, vel.size - 1, vel.size))
out.append(wf("tp_log", np.log10(tp).reshape(-1), "log10 of tone_peak_amp (prep_note, mean over seeds 1..4), key-major from A0, velocity grid tp_nv."))
# Sympathetic bank (SympatheticResonance): partials p <= 16 of each key below
# 7 kHz; the count without stiffness bounds every inharmonicity setting.
res_n = [int(min(16, np.floor(7000.0 / f0))) for f0 in keys[:, 1]]
out.append("// Partial slots of each key's sympathetic resonators, A0 first (min(16, 7000/f0)), and their total.\nres_n = (%s);\nres_total = %d;\n\n" % (",".join(str(n) for n in res_n), sum(res_n)))
undamped = [i for i in range(88) if keys[i, 21] == 0]
out.append("// First key (index from A0) without a damper; every key above has none either.\nres_first_undamped = %d;\n\n" % undamped[0])
out.append("// Number of soundboard modes.\nnb = %d;\n\n" % board.shape[0])
out.append(wf("board_f", board[:, 0], "Soundboard mode frequencies (Hz).", 17))
out.append(wf("board_sig", board[:, 1], "Soundboard mode decay rates (1/s).", 17))
out.append(wf("board_alr", AL.real, "Left amplitude, real part (output Im(A s), s driven by the force)."))
out.append(wf("board_ali", AL.imag, "Left amplitude, imaginary part."))
out.append(wf("board_arr", AR.real, "Right amplitude, real part."))
out.append(wf("board_ari", AR.imag, "Right amplitude, imaginary part."))
for r in range(4):
    for c, cn in enumerate("LR"):
        A = region_amps[2 * r + c]
        out.append(wf("board_r%d%s_re" % (r, cn), A.real, "Region %d, channel %s: amplitude, real part (Engine's head + tail response)." % (r, cn)))
        out.append(wf("board_r%d%s_im" % (r, cn), A.imag, "Region %d, channel %s: amplitude, imaginary part." % (r, cn)))
open(OUT, "w").write("".join(out))
print("wrote %s: board fit %.1f / %.1f dB, %d bytes" % (OUT, errs[0], errs[1], sum(len(x) for x in out)))
